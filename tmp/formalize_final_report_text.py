def delete_paragraph(paragraph):
    el = paragraph._element
    el.getparent().remove(el)
    paragraph._p = paragraph._element = None


def replace_by_prefix(doc, mapping):
    for p in doc.paragraphs:
        t = p.text.strip()
        for prefix, new_text in mapping.items():
            if t.startswith(prefix):
                p.text = new_text
                break


def remove_placeholder_and_supplement_blocks(doc):
    paras = list(doc.paragraphs)

    # Remove direct placeholder prompts. Captions such as "图题：" and "表：" are intentionally kept.
    for p in paras:
        t = p.text.strip()
        if t.startswith("【终稿") or t.startswith("【数据核对说明】") or t.startswith("终稿排版时"):
            delete_paragraph(p)

    # Remove the old "final checklist" and duplicated supplemental result block
    # placed after the references. The same results are already integrated into
    # Chapters 4-6.
    paras = list(doc.paragraphs)
    start = None
    end = None
    for i, p in enumerate(paras):
        text = p.text.strip()
        if text.startswith("终稿前补充清单"):
            start = i
        if start is not None and text.startswith("附录 E"):
            end = i
            break
    if start is not None and end is not None:
        for p in paras[start:end]:
            delete_paragraph(p)


def remove_long_duplicate_paragraphs(doc):
    seen = set()
    for p in list(doc.paragraphs):
        t = p.text.strip()
        if len(t) < 100 or t.startswith(("图", "表", "附录", "参考文献")):
            continue
        if t in seen:
            delete_paragraph(p)
        else:
            seen.add(t)


